pub fn dump(interfaces: &[IpcInterface]) -> String {
    let mut lines: Vec<String> = vec![HEADER.to_string(), String::new()];
    let mut sorted: Vec<&IpcInterface> = interfaces.iter().collect();
    sorted.sort_by(|a, b| a.name.cmp(&b.name));
    for iface in sorted {
        lines.push(format!("[{}]", iface.name));
        lines.push(format!("interface_id = {}", iface.interface_id));
        lines.push(String::new());
        let mut methods: Vec<&IpcMethod> = iface.methods.iter().collect();
        methods.sort_by(|a, b| a.name.cmp(&b.name));
        for method in methods {
            lines.push(format!("[{}.{}]", iface.name, method.name));
            lines.push(format!("funcHash = \"0x{:08X}\"", method.func_hash));
            lines.push(format!("wrapper_rva = \"0x{:X}\"", method.wrapper_rva));
            lines.push(format!("fencepost = \"0x{:08X}\"", method.fencepost));
            lines.push(format!("argc = {}", method.argc));
            lines.push(String::new());
        }
    }
    lines.join("\n")
}

pub fn method_count(interfaces: &[IpcInterface]) -> usize {
    interfaces.iter().map(|i| i.methods.len()).sum()
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = r#"
enum EIPCInterface : uint8 {
    IClientUser   = 1;
    IClientUtils  = 4;
};

interface IClientUser {
    void GetSteamID();
    void GetEncryptedAppTicket( in uint32 a, in uint32 b, out array<uint8> data );
    void Publish(unused int x);
};
"#;

    #[test]
    fn parses_interfaces_ids_and_arity() {
        let ifaces = parse_idl(SAMPLE);
        assert_eq!(ifaces.len(), 1);
        assert_eq!(ifaces[0].name, "IClientUser");
        assert_eq!(ifaces[0].interface_id, 1);
        let argc: Vec<(String, usize)> = ifaces[0]
            .methods
            .iter()
            .map(|m| (m.name.clone(), m.argc))
            .collect();
        assert_eq!(
            argc,
            vec![
                ("GetSteamID".to_string(), 0),
                ("GetEncryptedAppTicket".to_string(), 2),
                ("Publish".to_string(), 0),
            ]
        );
    }

    #[test]
    fn dump_matches_upstream_layout() {
        let interfaces = vec![IpcInterface {
            name: "IClientUser".into(),
            interface_id: 1,
            methods: vec![IpcMethod {
                name: "GetSteamID".into(),
                argc: 0,
                func_hash: 0xD6FC3200,
                fencepost: 0xD7058CA5,
                wrapper_rva: 0x7A23C0,
            }],
        }];
        let text = dump(&interfaces);
        assert!(text.contains("[IClientUser]\ninterface_id = 1\n"));
        assert!(text.contains("[IClientUser.GetSteamID]"));
        assert!(text.contains("funcHash = \"0xD6FC3200\""));
        assert!(text.contains("wrapper_rva = \"0x7A23C0\""));
        assert!(text.contains("fencepost = \"0xD7058CA5\""));
        assert!(text.contains("argc = 0"));
        assert!(text.ends_with('\n'));
    }
}