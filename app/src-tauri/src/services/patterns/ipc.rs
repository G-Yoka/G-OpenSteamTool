//! Zero-seed generator for the `ipc` channel, ported from
//! tools/pattern-tracker/ost_patterns/ipc.py.
//!
//! The `pattern` channel only says *where* a function lives. The IPC layer also
//! needs, per method, the two wire constants Steam puts on the request header
//! (`funcHash` / `fencepost`) plus the interface id and argument count. The
//! constants come from the wrapper function inside `steamclient64.dll`; the
//! interface id, the method list and `argc` come from the upstream IDL
//! (`IPCMessages.steamd`), which is why this channel needs one external input.

use std::collections::HashSet;

use super::pe::Pe;

const HEADER: &str = "# MACHINE-GENERATED by G-OpenSteamTool (ipc channel) - do not hand-edit\n# wire constants (funcHash/fencepost) extracted from steamclient64.dll wrappers";

#[derive(Debug, Clone)]
pub struct IpcMethod {
    pub name: String,
    pub argc: usize,
    pub func_hash: u32,
    pub fencepost: u32,
    pub wrapper_rva: u32,
}

#[derive(Debug, Clone)]
pub struct IpcInterface {
    pub name: String,
    pub interface_id: u32,
    pub methods: Vec<IpcMethod>,
}

/// `(interfaces, failures)`; interfaces with no resolvable method are dropped.
pub fn build(pe: &Pe, idl_text: &str) -> (Vec<IpcInterface>, Vec<String>) {
    let mut interfaces = parse_idl(idl_text);
    let method_names: HashSet<String> = interfaces
        .iter()
        .flat_map(|i| i.methods.iter().map(|m| m.name.clone()))
        .collect();
    let mut failures = Vec::new();
    for iface in interfaces.iter_mut() {
        let mut kept = Vec::new();
        for method in iface.methods.drain(..) {
            match extract(pe, &iface.name, &method, &method_names) {
                Ok(done) => kept.push(done),
                Err(err) => failures.push(err),
            }
        }
        iface.methods = kept;
    }
    interfaces.retain(|i| !i.methods.is_empty());
    (interfaces, failures)
}

/// Parse interfaces, their enum ids and method arity from the IDL.
pub fn parse_idl(text: &str) -> Vec<IpcInterface> {
    let ids = parse_interface_ids(text);
    let mut out = Vec::new();
    let bytes = text.as_bytes();
    let mut cursor = 0usize;
    while let Some(found) = find_keyword(bytes, b"interface", cursor) {
        let mut i = found + b"interface".len();
        i = skip_ws(bytes, i);
        let name_start = i;
        while i < bytes.len() && is_ident(bytes[i]) {
            i += 1;
        }
        if i == name_start {
            cursor = found + 1;
            continue;
        }
        let name = String::from_utf8_lossy(&bytes[name_start..i]).into_owned();
        i = skip_ws(bytes, i);
        if i >= bytes.len() || bytes[i] != b'{' {
            cursor = found + 1;
            continue;
        }
        let body_end = match matching_brace(bytes, i) {
            Some(v) => v,
            None => break,
        };
        let body = &text[i + 1..body_end];
        let mut methods = Vec::new();
        for (method_name, argc) in parse_methods(body) {
            methods.push(IpcMethod {
                name: method_name,
                argc,
                func_hash: 0,
                fencepost: 0,
                wrapper_rva: 0,
            });
        }
        if !methods.is_empty() {
            let id = ids.iter().find(|(n, _)| *n == name).map(|(_, v)| *v).unwrap_or(0);
            out.push(IpcInterface {
                name,
                interface_id: id,
                methods,
            });
        }
        cursor = body_end + 1;
    }
    out
}

fn parse_interface_ids(text: &str) -> Vec<(String, u32)> {
    let mut out = Vec::new();
    let Some(at) = text.find("EIPCInterface") else {
        return out;
    };
    let bytes = text.as_bytes();
    let mut i = at + "EIPCInterface".len();
    while i < bytes.len() && bytes[i] != b'{' {
        i += 1;
    }
    if i >= bytes.len() {
        return out;
    }
    let Some(end) = matching_brace(bytes, i) else {
        return out;
    };
    for line in text[i + 1..end].lines() {
        let line = line.trim().trim_end_matches([',', ';']).trim();
        if line.is_empty() {
            continue;
        }
        let Some((name, value)) = line.split_once('=') else {
            continue;
        };
        let name = name.trim();
        let value = value.trim().trim_end_matches([',', ';']).trim();
        if let Some(parsed) = parse_uint(value) {
            out.push((name.to_string(), parsed));
        }
    }
    out
}

fn parse_uint(text: &str) -> Option<u32> {
    let text = text.trim();
    if let Some(hex) = text.strip_prefix("0x").or_else(|| text.strip_prefix("0X")) {
        return u32::from_str_radix(hex, 16).ok();
    }
    text.parse::<u32>().ok()
}

/// `(name, argc)` for every `Type Name(params);` declaration in an interface body.
fn parse_methods(body: &str) -> Vec<(String, usize)> {
    let mut out = Vec::new();
    let bytes = body.as_bytes();
    let mut i = 0usize;
    while i < bytes.len() {
        if bytes[i] != b'(' {
            i += 1;
            continue;
        }
        let Some(close) = find_byte(bytes, b')', i + 1) else {
            break;
        };
        // Declaration must end with ';' after optional whitespace.
        let j = skip_ws(bytes, close + 1);
        if j >= bytes.len() || bytes[j] != b';' {
            i = i + 1;
            continue;
        }
        let Some(name) = identifier_before(bytes, i) else {
            i = close + 1;
            continue;
        };
        let params = &body[i + 1..close];
        let argc = params
            .split(',')
            .filter(|param| is_in_param(param))
            .count();
        out.push((name, argc));
        i = j + 1;
    }
    out
}

fn is_in_param(param: &str) -> bool {
    let trimmed = param.trim_start();
    let bytes = trimmed.as_bytes();
    if bytes.len() < 2 || !trimmed.starts_with("in") {
        return false;
    }
    // `\bin\b`: "in" must not be followed by an identifier character.
    match bytes.get(2) {
        Some(&b) => !is_ident(b),
        None => true,
    }
}

fn identifier_before(bytes: &[u8], paren: usize) -> Option<String> {
    let mut i = paren;
    while i > 0 && bytes[i - 1].is_ascii_whitespace() {
        i -= 1;
    }
    let end = i;
    while i > 0 && is_ident(bytes[i - 1]) {
        i -= 1;
    }
    if i == end || bytes[i].is_ascii_digit() {
        return None;
    }
    Some(String::from_utf8_lossy(&bytes[i..end]).into_owned())
}

fn is_ident(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

fn skip_ws(bytes: &[u8], mut i: usize) -> usize {
    while i < bytes.len() && bytes[i].is_ascii_whitespace() {
        i += 1;
    }
    i
}

fn find_byte(bytes: &[u8], needle: u8, from: usize) -> Option<usize> {
    bytes[from..].iter().position(|&b| b == needle).map(|p| p + from)
}

fn find_keyword(bytes: &[u8], needle: &[u8], from: usize) -> Option<usize> {
    let mut i = from;
    while i + needle.len() <= bytes.len() {
        if &bytes[i..i + needle.len()] == needle {
            let before_ok = i == 0 || !is_ident(bytes[i - 1]);
            let after = i + needle.len();
            let after_ok = after >= bytes.len() || !is_ident(bytes[after]);
            if before_ok && after_ok {
                return Some(i);
            }
        }
        i += 1;
    }
    None
}

fn matching_brace(bytes: &[u8], open: usize) -> Option<usize> {
    let mut depth = 0i32;
    for i in open..bytes.len() {
        match bytes[i] {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

// ---------------------------------------------------------------- extraction

fn wire_constants(body: &[u8]) -> Vec<(usize, u32)> {
    const PATTERNS: [(&[u8], usize); 3] = [
        (&[0xC7, 0x45], 7),
        (&[0xC7, 0x44, 0x24], 8),
        (&[0xC7, 0x84, 0x24], 11),
    ];
    let mut found = Vec::new();
    if body.len() < 4 {
        return found;
    }
    for i in 0..body.len() - 3 {
        if body[i] != 0xC7 {
            continue;
        }
        for (prefix, length) in PATTERNS {
            if i + length > body.len() {
                continue;
            }
            if &body[i..i + prefix.len()] != prefix {
                continue;
            }
            let at = i + length - 4;
            let value = u32::from_le_bytes([body[at], body[at + 1], body[at + 2], body[at + 3]]);
            if value != 0 {
                found.push((i, value));
            }
            break;
        }
    }
    found
}

fn find_wrapper(
    pe: &Pe,
    iface_name: &str,
    method_name: &str,
    method_names: &HashSet<String>,
) -> Result<u32, String> {
    let mut cands: HashSet<u32> = HashSet::new();
    for rva in pe.find_cstring(method_name) {
        for func in pe.funcs_referencing(rva) {
            cands.insert(func);
        }
    }
    if cands.len() > 1 {
        let mut narrowed: HashSet<u32> = HashSet::new();
        for func_rva in cands.iter() {
            let Some((begin, end)) = pe.func_at(*func_rva) else {
                continue;
            };
            let texts: HashSet<String> = pe.strings_in_func(begin, end, 4).into_values().collect();
            let named = texts.iter().filter(|t| method_names.contains(*t)).count();
            if texts.contains(iface_name) && named == 1 {
                narrowed.insert(*func_rva);
            }
        }
        cands = narrowed;
    }
    if cands.len() != 1 {
        return Err(format!(
            "{iface_name}::{method_name}: {} wrapper candidates",
            cands.len()
        ));
    }
    Ok(*cands.iter().next().unwrap())
}

fn extract(
    pe: &Pe,
    iface_name: &str,
    method: &IpcMethod,
    method_names: &HashSet<String>,
) -> Result<IpcMethod, String> {
    let wrapper = find_wrapper(pe, iface_name, &method.name, method_names)?;
    let (begin, end) = pe
        .func_at(wrapper)
        .ok_or_else(|| format!("{iface_name}::{}: wrapper 0x{wrapper:X} has no unwind info", method.name))?;
    let body = pe
        .read(begin, (end - begin) as usize)
        .map_err(|e| e.to_string())?;
    let constants = wire_constants(body);
    if constants.len() < 2 {
        return Err(format!(
            "{iface_name}::{}: expected funcHash+fencepost immediates, found {}",
            method.name,
            constants.len()
        ));
    }
    let mut done = method.clone();
    done.wrapper_rva = wrapper;
    done.func_hash = constants[0].1;
    done.fencepost = constants[1].1;
    Ok(done)
}

