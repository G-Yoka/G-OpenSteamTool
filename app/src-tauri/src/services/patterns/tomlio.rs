//! Pattern TOML writer, ported from tools/pattern-tracker/ost_patterns/tomlio.py.
//!
//! The table key is FNV-1a 32-bit of the hook name. `OpenSteamTool.dll` looks
//! patterns up by that key, so a wrong key makes the file load and then resolve
//! to nothing.

pub const GENERATED_HEADER: &str = "# MACHINE-GENERATED by G-OpenSteamTool - do not hand-edit";

#[derive(Debug, Clone, PartialEq)]
pub struct PatternEntry {
    pub name: String,
    pub rva: u32,
    pub sig: String,
}

/// FNV-1a 32-bit of the hook name, formatted as `0x%08X`.
pub fn hook_key(name: &str) -> String {
    let mut digest: u32 = 0x811C_9DC5;
    for byte in name.as_bytes() {
        digest ^= *byte as u32;
        digest = digest.wrapping_mul(0x0100_0193);
    }
    format!("0x{digest:08X}")
}

/// Serialise entries in the upstream-compatible layout.
pub fn dump_pattern(entries: &mut Vec<PatternEntry>) -> String {
    entries.sort_by(|a, b| a.name.cmp(&b.name));
    let mut lines: Vec<String> = vec![GENERATED_HEADER.to_string(), String::new()];
    for entry in entries.iter() {
        lines.push(format!("[{}]", hook_key(&entry.name)));
        lines.push(format!("name = \"{}\"", entry.name));
        lines.push(format!("rva = \"0x{:X}\"", entry.rva));
        lines.push(format!("sig = \"{}\"", entry.sig));
        lines.push(String::new());
    }
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Keys taken from the loader's own log lines; a mismatch means the DLL will
    /// report `PatternLoader: no entry for '<name>'` for every hook.
    #[test]
    fn hook_key_matches_loader() {
        let pairs = [
            ("GetAppByID", "0x3FC68546"),
            ("AddProtobufAsBinary", "0xD05E26A2"),
        ];
        for (name, expect) in pairs {
            assert_eq!(hook_key(name), expect, "key mismatch for {name}");
        }
    }

    #[test]
    fn dump_is_stable_and_ends_with_newline() {
        let mut entries = vec![
            PatternEntry { name: "B".into(), rva: 0x20, sig: "AA".into() },
            PatternEntry { name: "A".into(), rva: 0x10, sig: "BB".into() },
        ];
        let text = dump_pattern(&mut entries);
        assert!(text.starts_with(GENERATED_HEADER));
        assert!(text.ends_with('\n'));
        let a = text.find("name = \"A\"").unwrap();
        let b = text.find("name = \"B\"").unwrap();
        assert!(a < b, "entries must be sorted by name");
        assert!(text.contains("rva = \"0x10\""));
    }
}