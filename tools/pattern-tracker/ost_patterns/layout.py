"""Generator for ``SteamLayouts.gen.h`` — struct offsets as data, not code.

``CNetPacket``'s ``m_pubData``/``m_cubData`` moved between Steam client builds.
Reading them at the old offsets made the RecvPkt hook parse a bogus pointer and
take the client down (observed: read at ``0xFFFFFFFF``). The offsets are now a
generated artefact with recorded provenance, so the update path is
"re-observe -> regenerate -> rebuild" instead of "edit C++ and hope".

Observed values are supplied by the caller (they come from the runtime probe in
``Hooks_NetPacket.cpp``, built with ``/DOST_LAYOUT_PROBE``). This module only
turns them into the header and can verify an existing header against a set of
values, which is what a CI gate needs.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path


class LayoutError(RuntimeError):
    pass


@dataclass(frozen=True)
class NetPacketLayout:
    pub_data: int
    cub_data: int
    msghdr_emsg: int = 0x00
    msghdr_hdrlen: int = 0x04

    def validate(self) -> None:
        for name, value in (
            ("pub_data", self.pub_data),
            ("cub_data", self.cub_data),
            ("msghdr_emsg", self.msghdr_emsg),
            ("msghdr_hdrlen", self.msghdr_hdrlen),
        ):
            if value < 0 or value > 0x200:
                raise LayoutError(f"{name} offset {value:#x} is implausible")
        if self.pub_data % 8 != 0:
            raise LayoutError("pub_data must be pointer aligned")
        if self.cub_data % 4 != 0:
            raise LayoutError("cub_data must be dword aligned")


def emit_header(
    layout: NetPacketLayout,
    dll_sha256: str,
    client_version: str = "",
    observed_at: str = "",
    method: str = "",
) -> str:
    layout.validate()
    method = method or (
        "runtime probe of CNetPacket* inside the RecvPkt hook "
        "(pointer whose target starts with a dword carrying the EMsg high bit, "
        "followed by a header length)"
    )
    return f"""#pragma once

// ─────────────────────────────────────────────────────────────────────────────
// MACHINE-GENERATED by tools/pattern-tracker (`layout` command) - do not hand-edit
//
// Provenance
//   steamclient64.dll sha256 : {dll_sha256}
//   steam client version    : {client_version or "(unknown)"}
//   observed at             : {observed_at or "(unknown)"}
//   method                  : {method}
//
// Why this file exists
//   Valve shifts these fields between client builds. Hard-coding them in C++ means
//   every Steam update turns into a code change (and, before the probe, silently
//   wrong reads: m_pubData at the old +0x08 yielded 0xFFFFFFFF -> AV inside the
//   protobuf parser). Keeping the numbers as generated data makes the update path
//   "re-observe -> regenerate header -> rebuild", and the accessors in Structs.h
//   are the only place that knows about offsets.
// ─────────────────────────────────────────────────────────────────────────────

#define OST_LAYOUT_NETPACKET_PUBDATA 0x{layout.pub_data:X}u   // uint8*  payload pointer
#define OST_LAYOUT_NETPACKET_CUBDATA 0x{layout.cub_data:X}u   // uint32  payload size
#define OST_LAYOUT_MSGHDR_EMSG       0x{layout.msghdr_emsg:X}u   // uint32  EMsg | 0x80000000
#define OST_LAYOUT_MSGHDR_HDRLEN     0x{layout.msghdr_hdrlen:X}u   // uint32  protobuf header length

// Build marker: embedded into the DLL so the manager can report which layout a
// given binary was built with (see src/dllmain.cpp).
#define OST_LAYOUT_MARKER "{layout.pub_data:X}:{layout.cub_data:X}"
"""


_FIELD_RE = re.compile(r"#define\s+OST_LAYOUT_(\w+)\s+0x([0-9A-Fa-f]+)u")


def parse_header(text: str) -> NetPacketLayout:
    values: dict[str, int] = {}
    for name, hexval in _FIELD_RE.findall(text):
        values[name] = int(hexval, 16)
    missing = {
        "NETPACKET_PUBDATA",
        "NETPACKET_CUBDATA",
        "MSGHDR_EMSG",
        "MSGHDR_HDRLEN",
    } - values.keys()
    if missing:
        raise LayoutError(f"header is missing {sorted(missing)}")
    return NetPacketLayout(
        pub_data=values["NETPACKET_PUBDATA"],
        cub_data=values["NETPACKET_CUBDATA"],
        msghdr_emsg=values["MSGHDR_EMSG"],
        msghdr_hdrlen=values["MSGHDR_HDRLEN"],
    )


def verify_header(path: str | Path, expected: NetPacketLayout) -> list[str]:
    """Return a list of human-readable mismatches (empty means OK)."""
    actual = parse_header(Path(path).read_text(encoding="utf-8"))
    out = []
    for field in ("pub_data", "cub_data", "msghdr_emsg", "msghdr_hdrlen"):
        want = getattr(expected, field)
        got = getattr(actual, field)
        if want != got:
            out.append(f"{field}: header has 0x{got:X}, expected 0x{want:X}")
    return out
